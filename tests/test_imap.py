def test_findings_on_993_downgrades_plain_severity_to_low():
    h = _host_at(993)
    pr = {"reachable": True, "port": 993, "banner": "* OK ready",
          "preauth": False, "capabilities": ["AUTH=PLAIN"],
          "starttls": False, "logindisabled": False,
          "sasl": ["PLAIN"], "id": {}, "product": "", "version": "",
          "plaintext_login": "", "anonymous": False,
          "starttls_downgrade": False,
          "cram_md5_challenge": "", "digest_md5_challenge": ""}
    fs = imap.findings([h], {("10.0.0.9", 993): pr})
    plain = [f for f in fs if f["kind"] == "imap_sasl_mechanisms"]
    assert plain and plain[0]["severity"] == "low"
    # No cleartext / no-starttls finding on 993 - implicit TLS is fine.
    assert not any(f["kind"] == "imap_no_starttls" for f in fs)


def test_findings_to_vulns_source_and_severity():
    h = _host_at(143)
    pr = {"reachable": True, "port": 143, "banner": "* OK ready",
          "preauth": False, "capabilities": [], "starttls": False,
          "logindisabled": False, "sasl": [], "id": {}, "product": "",
          "version": "", "plaintext_login": "accepted", "anonymous": False,
          "starttls_downgrade": False,
          "cram_md5_challenge": "", "digest_md5_challenge": ""}
    fs = imap.findings([h], {("10.0.0.9", 143): pr})
    by_ip = imap.findings_to_vulns(fs)
    assert "10.0.0.9" in by_ip
    assert all(v.source == "imap" for v in by_ip["10.0.0.9"])


# --- capability / SASL parsing --------------------------------------------

def test_parse_capabilities_unions_bracket_and_untagged():
    data = (
        b"* OK [CAPABILITY IMAP4rev1 STARTTLS AUTH=PLAIN] Dovecot ready.\r\n"
        b"* CAPABILITY IMAP4rev1 AUTH=LOGIN AUTH=CRAM-MD5\r\n"
    )
    caps = imap._parse_capabilities(data)
    assert "STARTTLS" in caps and "AUTH=CRAM-MD5" in caps and "AUTH=LOGIN" in caps
    mechs = imap._sasl_mechs(caps)
    assert set(mechs) >= {"PLAIN", "LOGIN", "CRAM-MD5"}


def test_parse_id_returns_dict():
    data = b'* ID ("name" "Dovecot" "version" "2.3.16" "os" "Linux")\r\n'
    assert imap._parse_id(data) == {"name": "Dovecot", "version": "2.3.16", "os": "Linux"}


# --- is_imap classifier ---------------------------------------------------

def test_is_imap_respects_open_state_and_port():
    assert imap.is_imap(Port(portid=143, service="imap", state="open"))
    assert imap.is_imap(Port(portid=993, service="imaps", state="open"))
    assert not imap.is_imap(Port(portid=143, service="imap", state="closed"))
    assert not imap.is_imap(Port(portid=8080, service="http", state="open"))


# --- user-enum via monkeypatched socket ------------------------------------

def test_enum_users_via_monkeypatched_socket(monkeypatch):
    """LOGIN responses differ per user; enum_users detects the asymmetry."""
    valid = {"root", "postmaster"}

    class _FakeSock:
        def __init__(self, user_line: bytes):
            self._buf = b"* OK ready\r\n"
            self._reply_login = user_line

        def settimeout(self, _t): pass

        def sendall(self, data: bytes):
            if data.upper().startswith(b"U1 LOGIN"):
                self._buf += self._reply_login
            elif data.upper().startswith(b"X1 LOGOUT"):
                self._buf += b"x1 OK logout\r\n"

        def recv(self, n: int) -> bytes:
            out, self._buf = self._buf[:n], self._buf[n:]
            return out or b""

        def close(self): pass

    def fake_open(ip, port, timeout):
        # Peek at the pending username by scheduling a socket that answers
        # per user. We stash which user we are on via a mutable counter.
        u = _fake_open.next_user()
        line = b"u1 NO OK\r\n" if u in valid else b"u1 NO Authentication failed.\r\n"
        return _FakeSock(line)

    class _Counter:
        def __init__(self, users): self.users = list(users); self.i = 0
        def next_user(self):
            u = self.users[self.i % len(self.users)]
            self.i += 1
            return u

    # 1 valid vs 3 invalid: a clean majority so `distinguishes` isn't ambiguous.
    users = ["root", "alice", "bob", "carol"]
    valid = {"root"}
    _fake_open = _Counter(users)
    monkeypatch.setattr(imap, "_open_socket", fake_open)

    result = imap.enum_users("127.0.0.1", 143, users=users, timeout=1)
    assert result["distinguishes"] is True
    assert set(result["existing"]) == valid
